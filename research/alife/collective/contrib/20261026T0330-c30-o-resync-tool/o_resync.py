"""Component-normalised activity with a re-synchronised neutral shadow (after Channon 2001/2003 as restated
by Stout & Spector 2005), for census data (c30).
For each census interval j -> j+1 the shadow restarts from the REAL census j, resamples it neutrally for g
Wright-Fisher generations (population size N_{j+1} minus the copies of kinds new at j+1, which are added with
their real counts), and gives a shadow census j+1. Normalised activity of kind i:
    a_i(j) = sum_{k<=j} [count_i^real(k) - count_i^shadow(k)]
(growth beyond what drift alone would have produced over each interval). Threshold a0 = |min_i,j a_i(j)|, the
largest deficit seen in the run (Channon's choice); a kind is 'new adaptive' at the first census where a_i > a0.
Reports new adaptive kinds per window (by the census where they cross, and by their birth window).
Null check: rows generated by the same neutral resampling must give ~0 crossings (selftest)."""
import numpy as np


def resync_activity(rows, g=1, seed=0):
    rng = np.random.default_rng(seed); seen = set(); a = {}; birth = {}; amin = 0.0; hist = []
    prev = None
    for j, r in enumerate(rows):
        new = {k: n for k, n in r.items() if k not in seen}
        for k in r: birth.setdefault(k, j)
        if prev is None:
            sh = dict(r)
        else:
            N = sum(r.values()); M = max(0, N - sum(new.values()))
            labs = list(prev); p = np.array([prev[k] for k in labs], float)
            if p.sum() > 0 and M > 0:
                p /= p.sum()
                for _ in range(g):
                    d = rng.multinomial(M, p); p = d / max(1, d.sum())
                sh = {k: int(n) for k, n in zip(labs, d) if n > 0}
            else:
                sh = {}
            sh.update(new)
        for k in set(r) | set(sh):
            a[k] = a.get(k, 0.0) + r.get(k, 0) - sh.get(k, 0)
            if a[k] < amin: amin = a[k]
        hist.append({k: a[k] for k in r})        # activity of kinds present now
        seen |= set(r); prev = r
    return hist, birth, -amin


def _shadow_step(rng, prev, r, new, g):
    N = sum(r.values()); M = max(0, N - sum(new.values())); labs = list(prev); p = np.array([prev[k] for k in labs], float)
    sh = {}
    if p.sum() > 0 and M > 0:
        p /= p.sum()
        for _ in range(g):
            d = rng.multinomial(M, p); p = d / max(1, d.sum())
        sh = {k: int(n) for k, n in zip(labs, d) if n > 0}
    sh.update(new)
    return sh


def null_threshold(rows, g=1, seed=0, reps=3):
    """Largest normalised excess that one re-synchronised shadow reaches against another (no selection in
    either): the max over kinds and censuses, maximised over reps. Use it as a0 instead of Channon's |min a|."""
    best = 0.0
    for q in range(reps):
        r1 = np.random.default_rng(1000 + 2 * q + seed); r2 = np.random.default_rng(1001 + 2 * q + seed)
        seen = set(); a = {}; prev = None
        for r in rows:
            new = {k: n for k, n in r.items() if k not in seen}
            if prev is not None:
                s1 = _shadow_step(r1, prev, r, new, g); s2 = _shadow_step(r2, prev, r, new, g)
                for k in set(s1) | set(s2):
                    a[k] = a.get(k, 0.0) + s1.get(k, 0) - s2.get(k, 0)
                    if a[k] > best: best = a[k]
            seen |= set(r); prev = r
    return best


def new_adaptive(rows, g=1, seed=0, win=25, threshold="null"):
    hist, birth, a0c = resync_activity(rows, g, seed)
    a0 = null_threshold(rows, g, seed) if threshold == "null" else a0c
    crossed = {}
    for j, h in enumerate(hist):
        for k, v in h.items():
            if v > a0 and k not in crossed: crossed[k] = j
    nb = (len(rows) + win - 1) // win
    by_cross = np.bincount([j // win for j in crossed.values()], minlength=nb)[:nb]
    by_birth = np.bincount([birth[k] // win for k in crossed], minlength=nb)[:nb]
    return dict(a0=a0, a0_channon=a0c, n_new=len(crossed), by_cross=by_cross.tolist(), by_birth=by_birth.tolist())


def _neutral_rows(seed, J=200, N=2000, mu=0.002, g=5):
    """Synthetic neutral censuses: WF drift for g generations per census, mutation to new kinds."""
    rng = np.random.default_rng(seed); kinds = np.zeros(N, np.int64); nxt = 1; rows = []
    for j in range(J):
        for _ in range(g):
            kinds = kinds[rng.integers(0, N, N)]
            m = rng.random(N) < mu; kinds[m] = np.arange(nxt, nxt + m.sum()); nxt += m.sum()
        u, c = np.unique(kinds, return_counts=True); rows.append({int(k): int(n) for k, n in zip(u, c) if n >= 3})
    return rows


def _selected_rows(seed, J=200, N=2000, mu=0.002, g=5, s=0.1):
    """Same, with each new mutant fitter than its parent by s (recurrent sweeps)."""
    rng = np.random.default_rng(seed); kinds = np.zeros(N, np.int64); fit = np.ones(N); nxt = 1; rows = []
    for j in range(J):
        for _ in range(g):
            idx = rng.choice(N, N, p=fit / fit.sum()); kinds = kinds[idx]; fit = fit[idx]
            m = rng.random(N) < mu; kinds[m] = np.arange(nxt, nxt + m.sum()); fit[m] *= 1 + s; nxt += m.sum(); fit /= fit.max()
        u, c = np.unique(kinds, return_counts=True); rows.append({int(k): int(n) for k, n in zip(u, c) if n >= 3})
    return rows


if __name__ == "__main__":
    import sys
    if "--selftest" in sys.argv:
        for name, f in (("neutral", _neutral_rows), ("sweeps s=0.1", _selected_rows)):
            for sd in (1, 2):
                rows = f(sd)
                for g in (1, 5):
                    for th in ("channon", "null"):
                        r = new_adaptive(rows, g=g, win=50, threshold=th)
                        print(f"{name} seed {sd}, shadow g={g} (true g=5), threshold {th}: a0={r['a0']:.0f} new adaptive kinds {r['n_new']} by window {r['by_cross']}")
