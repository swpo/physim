POD_RUN_SH = """#!/bin/bash
# pod_run.sh — island main loop. Usage: ./pod_run.sh <first_gen> <last_gen>
# GENERATED by blobkit.deploy_tools.make_bundle (blobkit {version}).
# Requires island_config.json beside this script. Idempotent per gen.
set -u
cd "$(dirname "$0")"
# Thread pins: parallelism is PROCESS-level (n_workers shards). Letting BLAS/
# FFT spawn threads per worker over-subscribes the pod and thrashes (fleet
# lesson). Keep these at 1; scale with n_workers instead.
export OMP_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
export MKL_NUM_THREADS=1
export VECLIB_MAXIMUM_THREADS=1
export NUMEXPR_NUM_THREADS=1
PY=${{PY:-python3}}
OUT=$($PY -c "import json;c=json.load(open('island_config.json'));print(c.get('out_dir') or 'out')")
mkdir -p "$OUT"
FIRST=${{1:-1}}; LAST=${{2:-25}}
run_shards () {{  # tag
  local TAG=$1
  ls "$OUT"/jobs/${{TAG}}_w*.json >/dev/null 2>&1 || return 0
  for W in "$OUT"/jobs/${{TAG}}_w*.json; do
    nohup $PY pod_worker.py "$W" > "$OUT"/w_${{TAG}}_$(basename $W .json).log 2>&1 &
  done
  while pgrep -f "pod_worker.py $OUT/jobs/${{TAG}}_" >/dev/null; do sleep 60; done
  for W in "$OUT"/jobs/${{TAG}}_w*.json; do   # drain (idempotent)
    $PY pod_worker.py "$W" >> "$OUT"/drain_${{TAG}}.log 2>&1
  done
}}
if [ "$FIRST" -eq 0 ]; then
  $PY pod_gen.py init >> "$OUT"/driver.log 2>&1
  run_shards g0
  $PY pod_gen.py ingest 0 >> "$OUT"/driver.log 2>&1
  run_shards s2g0
  $PY pod_gen.py ingest2 0 >> "$OUT"/driver.log 2>&1
  run_shards s3g0
  $PY pod_gen.py ingest3 0 >> "$OUT"/driver.log 2>&1
  run_shards laneg0
  FIRST=1
fi
for GEN in $(seq $FIRST $LAST); do
  $PY pod_gen.py breed $GEN >> "$OUT"/driver.log 2>&1
  run_shards g${{GEN}}
  $PY pod_gen.py ingest $GEN >> "$OUT"/driver.log 2>&1
  run_shards s2g${{GEN}}
  $PY pod_gen.py ingest2 $GEN >> "$OUT"/driver.log 2>&1
  run_shards s3g${{GEN}}
  $PY pod_gen.py ingest3 $GEN >> "$OUT"/driver.log 2>&1
  run_shards laneg${{GEN}}
  echo "GEN_${{GEN}}_DONE $(date)" >> "$OUT"/driver.log
done
echo "POD_RUN_DONE $FIRST-$LAST $(date)" >> "$OUT"/driver.log
"""

POD_RUN_BATCH_SH = """#!/bin/bash
# pod_run_batch.sh — island main loop, BATCHED-LADDER mode (blobkit {version}).
# GENERATED by blobkit.deploy_tools.make_bundle (sim_backend=gpu_batch).
# One run_assay_batch sweep per gen: all screen lanes (+ pending confirms if
# confirms=async) ride one padded device tensor down the locked ladder.
# The GPU does the stepping; battery_procs CPU processes do the batteries.
# Usage: ./pod_run_batch.sh <first_gen> <last_gen>
set -u
cd "$(dirname "$0")"
export OMP_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
export MKL_NUM_THREADS=1
export VECLIB_MAXIMUM_THREADS=1
export NUMEXPR_NUM_THREADS=1
PY=${{PY:-python3}}
OUT=$($PY -c "import json;c=json.load(open('island_config.json'));print(c.get('out_dir') or 'out')")
mkdir -p "$OUT"
ASYNC=$($PY -c "import json;c=json.load(open('island_config.json'));print(1 if c.get('confirms')=='async' else 0)")
FIRST=${{1:-1}}; LAST=${{2:-25}}
run_batch () {{  # tag -> one batched sweep over all that tag's shards
  local TAG=$1
  ls "$OUT"/jobs/${{TAG}}_w*.json >/dev/null 2>&1 || return 0
  $PY pod_worker_batch.py "$OUT"/jobs/${{TAG}}_w*.json \
      > "$OUT"/wb_${{TAG}}.log 2>&1
}}
run_gen_batch () {{  # gen -> screens (+ pending confirms when async)
  local GEN=$1
  if [ "$ASYNC" -eq 1 ]; then
    $PY pod_gen_batch.py collect $GEN >> "$OUT"/driver.log 2>&1
    local FILES=$($PY -c "import json;print(' '.join(json.load(open('$OUT/jobs/batch_g$GEN.json'))))")
    [ -n "$FILES" ] && $PY pod_worker_batch.py $FILES > "$OUT"/wb_g${{GEN}}.log 2>&1
  else
    run_batch g${{GEN}}
  fi
}}
if [ "$FIRST" -eq 0 ]; then
  G0MODE=$($PY -c "import json;c=json.load(open('island_config.json'));print(c.get('g0') or 'eval')")
  if [ "$G0MODE" = "import" ]; then
    echo "g0=import: run  $PY pod_gen_batch.py g0import <archive.json>  once, then start at gen 1" >> "$OUT"/driver.log
  else
    $PY pod_gen.py init >> "$OUT"/driver.log 2>&1
    run_batch g0
    $PY pod_gen.py ingest 0 >> "$OUT"/driver.log 2>&1
    if [ "$ASYNC" -eq 0 ]; then
      run_batch s2g0
      $PY pod_gen.py ingest2 0 >> "$OUT"/driver.log 2>&1
      run_batch s3g0
      $PY pod_gen.py ingest3 0 >> "$OUT"/driver.log 2>&1
      run_batch laneg0
    fi
  fi
  FIRST=1
fi
for GEN in $(seq $FIRST $LAST); do
  $PY pod_gen.py breed $GEN >> "$OUT"/driver.log 2>&1
  run_gen_batch $GEN
  # ingest earlier gens' confirms that rode this sweep (async), then this gen
  if [ "$ASYNC" -eq 1 ]; then
    PREV=$((GEN-1))
    if [ "$PREV" -ge 0 ]; then
      $PY pod_gen.py ingest2 $PREV >> "$OUT"/driver.log 2>&1
      $PY pod_gen.py ingest3 $PREV >> "$OUT"/driver.log 2>&1
    fi
    $PY pod_gen.py ingest $GEN >> "$OUT"/driver.log 2>&1
  else
    $PY pod_gen.py ingest $GEN >> "$OUT"/driver.log 2>&1
    run_batch s2g${{GEN}}
    $PY pod_gen.py ingest2 $GEN >> "$OUT"/driver.log 2>&1
    run_batch s3g${{GEN}}
    $PY pod_gen.py ingest3 $GEN >> "$OUT"/driver.log 2>&1
    run_batch laneg${{GEN}}
  fi
  echo "GEN_${{GEN}}_DONE $(date)" >> "$OUT"/driver.log
done
echo "POD_RUN_DONE $FIRST-$LAST $(date)" >> "$OUT"/driver.log
"""

