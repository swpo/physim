"""blobkit.deploy_tools — fleet bundle generator (blobkit 0.2, T4).

make_bundle(out_dir) emits a minimal island-fleet bundle BUILT FROM the
installed blobkit package. This retires the legacy tree-snapshot deploy
bundle (probes/blobs/l0/deepsearch/deploy/) for FUTURE runs: the science
stack ships as the pip-installable blobkit wheel (locked, verify_locks()
travels with it) instead of loose lib/ copies; only the search-runtime
scripts ride along.

Bundle layout (out_dir/):
    wheel/blobkit-<v>-*.whl   built if a wheel builder is available, else
    pkg/                      pip-installable source copy of the package
                              (pip install ./pkg) — always emitted
    pod_lib.py                ADAPTED runtime (imports blobkit; assay via
                              assay_v2b.run_assay_b(backend=sim_backend))
    pod_gen.py, pod_worker.py, pod_smoke.py, merge_islands.py
                              VERBATIM fleet-certified scripts
    lib/genome.py, lib/operators_lib.py
                              2-line alias shims -> blobkit modules (the
                              verbatim scripts keep `import genome` working)
    lib/funnel.py, lib/sampler.py, lib/ds2_ops.py
                              VERBATIM certified search stack (not yet
                              promoted into the package; hashes pinned)
    pod_run.sh                GENERATED: thread-pin exports (OMP/OPENBLAS/
                              MKL/VECLIB=1 — process-level parallelism only,
                              the fleet thrash lesson) + the certified loop
    island_config.template.json
                              GENERATED: adds "sim_backend" ("cpu"|"gpu");
                              lane knobs default OFF (l192_per_gen=0,
                              longh_top=0) — long-horizon/L192 lanes are the
                              GPU backend's job on future fleets
    seeds/                    packaged world registry (all certified worlds
                              + blk_engine_10748 block primitive), plus
                              optional extra_seeds copies
    requirements.txt, README.md, bundle_hashes.txt

Templates live in blobkit/data/fleet/ (package data): pod_lib.py carries the
[fleetbundle F1/F2] adaptation markers; the rest are byte-verbatim copies of
the running fleet's deploy/ scripts (hashes in MANIFEST 0.2).
"""
