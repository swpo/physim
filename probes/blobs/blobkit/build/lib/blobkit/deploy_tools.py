def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def _copy_pkg(out_pkg):
    """Copy the INSTALLED blobkit package into out_pkg/ as a pip-installable
    source dir (hermetic: no dependency on the dev tree)."""
    dst = os.path.join(out_pkg, "blobkit")
    shutil.copytree(_PKG, dst,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    pyproject = f"""[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "blobkit"
version = "{__version__}"
description = "Certified physim blob core (fleet bundle copy)."
requires-python = ">=3.9"
dependencies = ["numpy", "scipy"]

[project.optional-dependencies]
gpu = ["jax[cuda12]==0.4.38"]

[tool.setuptools]
packages = ["blobkit", "blobkit.soup"]

[tool.setuptools.package-data]
blobkit = ["data/*.npz", "data/worlds/*.json", "data/fleet/*", "_locks.json"]
"""
    with open(os.path.join(out_pkg, "pyproject.toml"), "w") as f:
        f.write(pyproject)
    return out_pkg


def _try_wheel(pkg_dir, wheel_dir):
    """Best-effort wheel build from pkg_dir. Returns wheel path or None."""
    os.makedirs(wheel_dir, exist_ok=True)
    cmds = [
        ["uv", "build", "--wheel", "--out-dir", wheel_dir, pkg_dir],
        [sys.executable, "-m", "build", "--wheel", "--no-isolation",
         "--outdir", wheel_dir, pkg_dir],
        [sys.executable, "-m", "pip", "wheel", "--no-deps",
         "-w", wheel_dir, pkg_dir],
    ]
    for cmd in cmds:
        try:
            r = subprocess.run(cmd, capture_output=True, text=True,
                               timeout=600)
        except (FileNotFoundError, subprocess.TimeoutExpired):
            continue
        if r.returncode == 0:
            whl = sorted(glob.glob(os.path.join(wheel_dir, "blobkit-*.whl")))
            if whl:
                return whl[-1]
    return None


def _export_seeds(seeds_dir, extra_seeds=None):
    """Seed pool = every packaged world (certified registry) + the
    blk_engine_10748 block primitive + optional extra dir of genome JSONs."""
    from . import worlds as W
    os.makedirs(seeds_dir, exist_ok=True)
    n = 0
    for name in W.names():
        g = W.load(name)
        with open(os.path.join(seeds_dir, f"{name}.json"), "w") as f:
            json.dump(g, f)
        n += 1
    blk = W.load("engine_10748")
    blk["id"] = "blk_engine_10748"
    with open(os.path.join(seeds_dir, "blk_engine_10748.json"), "w") as f:
        json.dump(blk, f)
    n += 1
    for src in sorted(glob.glob(os.path.join(extra_seeds, "*.json"))) \
            if extra_seeds else []:
        shutil.copy2(src, os.path.join(seeds_dir, os.path.basename(src)))
        n += 1
    return n


def make_bundle(out_dir, backend="cpu", extra_seeds=None, wheel=True,
                overwrite=False):
    """Emit a fleet bundle into out_dir. Returns a receipt dict."""
    if os.path.exists(out_dir):
        if not overwrite and os.listdir(out_dir):
            raise FileExistsError(f"{out_dir} exists and is not empty "
                                  "(overwrite=True to replace)")
        if overwrite:
            shutil.rmtree(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    receipt = dict(blobkit=__version__, backend=backend, files={})

    # 1. pip-installable package copy (+ wheel if a builder is available)
    pkg_dir = _copy_pkg(os.path.join(out_dir, "pkg"))
    whl = _try_wheel(pkg_dir, os.path.join(out_dir, "wheel")) if wheel else None
    receipt["wheel"] = os.path.basename(whl) if whl else None
    if whl is None and wheel:
        receipt["wheel_note"] = ("no wheel builder available (uv/build/pip); "
                                 "install with: pip install ./pkg")

    # 2. runtime scripts: adapted pod_lib + verbatim certified scripts
    shutil.copy2(os.path.join(_FLEET, "pod_lib.py"),
                 os.path.join(out_dir, "pod_lib.py"))
    for name in VERBATIM_SCRIPTS:
        shutil.copy2(os.path.join(_FLEET, name), os.path.join(out_dir, name))
    if backend == "gpu_batch":                       # 0.3 batched-ladder mode
        for name in BATCH_SCRIPTS:
            shutil.copy2(os.path.join(_FLEET, name),
                         os.path.join(out_dir, name))
    lib_dir = os.path.join(out_dir, "lib")
    os.makedirs(lib_dir, exist_ok=True)
    for name in VERBATIM_LIB:
        shutil.copy2(os.path.join(_FLEET, name), os.path.join(lib_dir, name))
    for shim, target in SHIMS.items():
        with open(os.path.join(lib_dir, shim), "w") as f:
            f.write(_SHIM.format(name=shim[:-3], target=target))

    # 3. generated: pod_run.sh (thread pins), config template (sim_backend,
    #    lanes off), requirements, README
    pr = os.path.join(out_dir, "pod_run.sh")
    with open(pr, "w") as f:
        f.write(POD_RUN_SH.format(version=__version__))
    os.chmod(pr, 0o755)
    if backend == "gpu_batch":                       # 0.3 batched main loop
        prb = os.path.join(out_dir, "pod_run_batch.sh")
        with open(prb, "w") as f:
            f.write(POD_RUN_BATCH_SH.format(version=__version__))
        os.chmod(prb, 0o755)
    cfg = dict(CONFIG_TEMPLATE)
    cfg["sim_backend"] = backend
    if backend == "gpu_batch":
        cfg["batch_lanes"] = 32
        cfg["batch_dtype"] = "f32"
        cfg["battery_procs"] = 8
        cfg["confirms"] = "sync"
        cfg["g0"] = "eval"
        cfg["_note_batch"] = (
            "gpu_batch (0.3): pod_run_batch.sh drives whole generations "
            "through run_assay_batch (one device tensor; pod_worker_batch). "
            "batch_lanes = max lanes per tensor (B pads to 4/8/16/32); "
            "battery_procs = CPU pool for the locked per-lane batteries; "
            "confirms='async' folds gen N's s2/s3/lane confirms into gen "
            "N+1's sweep (one batch call per gen; elites enter the block "
            "library one gen late — order-tolerant); g0='import' seeds the "
            "archive from a donor via pod_gen_batch.py g0import. "
            "PERF floor: verify_v03/PERF_REFERENCE.json (deploy smoke "
            "fails below it on GPU devices).")
    with open(os.path.join(out_dir, "island_config.template.json"), "w") as f:
        json.dump(cfg, f, indent=1)
    with open(os.path.join(out_dir, "requirements.txt"), "w") as f:
        f.write("numpy>=1.26\nscipy>=1.11\n"
                "# science stack: pip install wheel/blobkit-*.whl "
                "(or ./pkg)\n# gpu islands: pip install 'blobkit[gpu]'\n")
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write(README.format(version=__version__))

    # 4. seeds from the packaged registry
    receipt["n_seeds"] = _export_seeds(os.path.join(out_dir, "seeds"),
                                       extra_seeds)

    # 5. integrity manifest over everything emitted
    lines = []
    for root, _dirs, files in os.walk(out_dir):
        for fn in sorted(files):
            if fn == "bundle_hashes.txt":
                continue
            fp = os.path.join(root, fn)
            rel = os.path.relpath(fp, out_dir)
            digest = _sha256(fp)
            lines.append(f"{digest}  {rel}")
            receipt["files"][rel] = digest[:12]
    with open(os.path.join(out_dir, "bundle_hashes.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    receipt["n_files"] = len(receipt["files"])
    receipt["out_dir"] = os.path.abspath(out_dir)
    return receipt


def main():
    import argparse
    ap = argparse.ArgumentParser(description="emit a blobkit fleet bundle")
    ap.add_argument("out_dir")
    ap.add_argument("--backend", default="cpu",
                    choices=("cpu", "gpu", "gpu_batch"))
    ap.add_argument("--extra-seeds", default=None)
    ap.add_argument("--no-wheel", action="store_true")
    ap.add_argument("--overwrite", action="store_true")
    a = ap.parse_args()
    r = make_bundle(a.out_dir, backend=a.backend, extra_seeds=a.extra_seeds,
                    wheel=not a.no_wheel, overwrite=a.overwrite)
    print(json.dumps({k: v for k, v in r.items() if k != "files"}, indent=1))


if __name__ == "__main__":
    main()
